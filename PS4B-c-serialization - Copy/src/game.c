/*
  Creates a new game, allowing player to input character icon, and starts play.
*/
void new_game() {
  srand(time(NULL));

  char c;
  printf("Input character icon: ");
  scanf("%c", &c);
  getchar(); //discard newline in buffer.
  
  // Player starts in top right corner.
  player o1 = {0,0,c};

  // Place treasure at a random location, with a random value.
  treasure o2 = {rand() % 10, rand() % 10,'C',((float) (rand() % 1000)) / 100, '$'};

  play_game(o1,o2);
}

/*
 Saves game state (player struct and treasure struct) to a file.
 Takes in player input for file name to save into.
*/
void save_game(player p, treasure t) {
    Buffer *b = new_buffer();
    serialize_P(&p, b);
    serialize_T(&t, b);

    char filepath[100];
    printf("Filepath to save?: ");
    scanf("%s", filepath);
    
    
    int fd = open(filepath,  O_RDWR | O_CREAT | O_TRUNC, 0644);
    serialize_file(fd, b);
    printf("size: %ld %ld\n", b->size, b->top);
 
    close(fd);

}

/*
  Loads a game state from a specified filepath.
  The file needs to be generated by the corresponding save_game() function.
*/
void load_game() {
  printf("Saved Game Filepath?: ");
  char filepath[100];
  scanf("%s", filepath);
  getchar();
  
  printf("Loading game from %s\n", filepath);

  player o1;
  treasure o2;
  
  Buffer *nb = new_buffer();
  int fd2 = open(filepath, O_RDWR, 0644);
  deserialize_file(fd2, nb);

  deserialize_T(&o2, nb);
  deserialize_P(&o1,nb);

  

  play_game(o1,o2);
}


/*
  Displays a 10x10 board of x characters.
  Also displays the location of the player.
*/
void print_board(player p) {
  for(int i = 0; i < 10; i++) {
    for(int j = 0; j < 10; j++) {
      if(p.x == j && p.y == i) {
	      printf(" %c ", p.icon);
      } else {
	      printf(" x ");
      }
    }
    printf("\n");
  }
}

/*
  Main game logic. 
  1) Displays the board.
  2) Allows player to input movement direction or save.
  3) Performs any nessecary logic-- updating player location, saving state
  4) Checks if player is on the treasure, if so, we win!
*/
void play_game(player p, treasure t) {
  while(1) {
    print_board(p);

    printf("Command [u,d,l,r,s]: ");
    char c;
    scanf("%c", &c);
    getchar(); //discard newline in buffer.s
  
    switch(c) {
    case 'u':
      p.y--;
      break;
    case 'd':
      p.y++;
      break;
    case 'r':
      p.x++;
      break;
    case 'l':
      p.x--;
      break;
    case 's':
      save_game(p,t);
      break;
    default:
      printf("ERROR: unrecognized command\n");
      return;
    }
    
    if(p.x == t.x && p.y == t.y) {
      printf("FOUND TREASURE!! WORTH: %c%f\n",t.currency, t.value);
      break;
    } else {
      printf("YOU ARE %d MOVES AWAY FROM TREASURE\n", abs(p.x - t.x) + abs(p.y-t.y));
    }
  }
}

/*
 Main function allows players to start a new game, or load existing game.
*/
int main(void) {
  printf("New Game (N) or Load Game (L)?: ");

  char opt;
  scanf("%c", &opt);
  getchar(); //discard newline in buffer.
  
  if(opt == 'N') {
    new_game();
  } else if (opt == 'L') {
    load_game();
  } else {
    printf("ERROR: unrecognized option\n");
    return 1;
  }
  
}
